import re as _re
def _md(node):
    """Turn **bold** inside plain body strings into real Word bold runs."""
    if isinstance(node, str):
        if "**" not in node:
            return node
        parts = _re.split(r"\*\*(.+?)\*\*", node)
        out = []
        for i, seg in enumerate(parts):
            if not seg:
                continue
            out.append({"t": seg, "b": True} if i % 2 else seg)
        return out
    if isinstance(node, list):
        flat = []
        for x in node:
            r = _md(x)
            flat.extend(r) if isinstance(r, list) and isinstance(x, str) else flat.append(r)
        return flat
    if isinstance(node, dict):
        return {k: (_md(v) if k in ("bullet",) else v) for k, v in node.items()}
    return node

